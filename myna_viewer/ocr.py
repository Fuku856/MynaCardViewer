"""オープンソースの OCR エンジン Tesseract（Apache-2.0）で券面の氏名・住所画像を文字にする。

履歴に残す「氏名の冒頭一字」「住所の都道府県」を得るためだけに使う。
- Tesseract 本体と日本語の学習データはアプリに同梱し（vendor/tesseract、exe では展開先）、
  OS やクラウドの OCR は使わない。
- 画像はファイルに書かず標準入力で渡し、結果は標準出力で受け取る（ネットワークを使う入力形式は使わない）。
- 前処理を何通りか試し、条件 (accept) を満たした最初の結果を採用する。
OCR が使えない環境や読めなかった場合は空文字を返す。
"""
import io
import os
import re
import subprocess  # nosec B404 （同梱した実行ファイルを引数リストで呼ぶだけ。シェルは使わない）
import sys

from PIL import Image, ImageFilter, ImageOps, ImageStat

from .imaging import TEXT_IMAGE_FORMATS, open_image

TIMEOUT_SEC = 20

PREFECTURES = [
    '北海道', '青森県', '岩手県', '宮城県', '秋田県', '山形県', '福島県', '茨城県', '栃木県', '群馬県',
    '埼玉県', '千葉県', '東京都', '神奈川県', '新潟県', '富山県', '石川県', '福井県', '山梨県', '長野県',
    '岐阜県', '静岡県', '愛知県', '三重県', '滋賀県', '京都府', '大阪府', '兵庫県', '奈良県', '和歌山県',
    '鳥取県', '島根県', '岡山県', '広島県', '山口県', '徳島県', '香川県', '愛媛県', '高知県', '福岡県',
    '佐賀県', '長崎県', '熊本県', '大分県', '宮崎県', '鹿児島県', '沖縄県',
]
_JP_CHAR = re.compile(r'[぀-ヿ㐀-鿿豈-﫿]')


def tesseract_dir():
    """同梱した Tesseract のフォルダ。exe では展開先の tesseract、開発時は vendor/tesseract。"""
    if hasattr(sys, '_MEIPASS'):
        return os.path.join(sys._MEIPASS, 'tesseract')
    return os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'vendor', 'tesseract')


def available():
    d = tesseract_dir()
    return os.path.isfile(os.path.join(d, 'tesseract.exe')) and \
        os.path.isfile(os.path.join(d, 'tessdata', 'jpn.traineddata'))


PNG_SIGNATURE = b'\x89PNG\r\n\x1a\n'


def _recognize(png: bytes):
    d = tesseract_dir()
    exe = os.path.join(d, 'tesseract.exe')
    if not available():
        raise RuntimeError('Tesseract is not bundled')
    # Tesseract は標準入力が画像でないと「画像ファイル名（URL も可）の一覧」として読むため、
    # 自分で作った PNG 以外は絶対に渡さない
    if not png.startswith(PNG_SIGNATURE):
        raise ValueError('only PNG generated by this app may be passed to tesseract')
    # 環境変数は最小限だけ渡す（プロキシ設定なども引き継がない）
    env = {'SystemRoot': os.environ.get('SystemRoot', r'C:\Windows'), 'OMP_THREAD_LIMIT': '1'}
    result = subprocess.run(  # nosec B603 （固定パスの実行ファイルと固定の引数）
        [exe, 'stdin', 'stdout', '-l', 'jpn', '--psm', '6', '--tessdata-dir', os.path.join(d, 'tessdata')],
        input=png, capture_output=True, timeout=TIMEOUT_SEC, env=env, cwd=d,
        creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0))
    if result.returncode != 0:
        raise RuntimeError('tesseract exited with %d' % result.returncode)
    return result.stdout.decode('utf-8', 'replace')


def _png(img):
    buf = io.BytesIO()
    img.save(buf, 'PNG')
    return buf.getvalue()


def _sources(img):
    """白地に黒文字のグレースケール画像の候補を返す。"""
    out = []
    if 'A' in img.getbands() or (img.mode == 'P' and 'transparency' in img.info):
        rgba = img.convert('RGBA')
        flat = Image.new('RGB', rgba.size, 'white')
        flat.paste(rgba, mask=rgba.getchannel('A'))
        out.append(('flat', flat.convert('L')))
        out.append(('alpha', ImageOps.invert(rgba.getchannel('A'))))  # 透過の濃さを文字として扱う
    else:
        out.append(('plain', img.convert('L')))
    fixed = []
    for name, g in out:
        if ImageStat.Stat(g).mean[0] < 128:  # 黒地に白文字なら反転
            g, name = ImageOps.invert(g), name + '-inv'
        fixed.append((name, g))
    return fixed


def _variants(img):
    for src_name, g in _sources(img):
        ink = g.point(lambda v: 255 if v < 160 else 0)
        box = ink.getbbox()
        if box is None:
            yield src_name + ' empty', None
            continue
        crop = ImageOps.expand(g.crop(box), 16, fill=255)
        yield src_name + ' as-is', g
        for target in (48, 96, 32, 144):
            s = target / crop.height
            if not 0.1 <= s <= 8:
                continue
            r = crop.resize((max(1, int(crop.width * s)), target), Image.Resampling.LANCZOS)
            yield '%s crop h%d' % (src_name, target), r
            yield '%s crop h%d blur' % (src_name, target), r.filter(ImageFilter.GaussianBlur(0.8))


def _results(image_bytes: bytes, log):
    """前処理の方式ごとに OCR し、空白を除いた文字列を順に返す。

    log には個人情報を含まない診断情報（画像形式・各方式の文字数）だけを渡す。
    """
    if not image_bytes:
        log('  no image data')
        return
    try:
        img = open_image(image_bytes, TEXT_IMAGE_FORMATS)
    except Exception as e:  # noqa: BLE001
        log('  image open failed: %s' % type(e).__name__)
        return
    log('  format=%s mode=%s size=%dx%d transparency=%s' % (
        img.format, img.mode, img.width, img.height, 'transparency' in img.info))
    for name, v in _variants(img):
        if v is None:
            log('  %-24s no ink' % name)
            continue
        try:
            text = re.sub(r'\s+', '', _recognize(_png(v)))
        except Exception as e:  # noqa: BLE001 - OCR は履歴用の補助なので失敗しても読み取りは続ける
            log('  %-24s error %s: %s' % (name, type(e).__name__, str(e)[:80]))
            continue
        log('  %-24s %dx%d chars=%d jp=%d' % (name, v.width, v.height, len(text), len(_JP_CHAR.findall(text))))
        yield text


def _logger(diag):
    return diag.append if diag is not None else (lambda s: None)


def recognize(image_bytes: bytes, accept=None, diag=None):
    """accept(text) が真になった最初の結果を返す（省略時は日本語の文字を含めば採用）。"""
    accept = accept or (lambda t: bool(_JP_CHAR.search(t)))
    for text in _results(image_bytes, _logger(diag)):
        if accept(text):
            return text
    return ''


def name_initial(image_bytes: bytes, diag=None, votes=5):
    """氏名画像の冒頭一字。前処理を変えた複数の結果で多数決を取り、形の似た字への誤読を減らす。"""
    counts = {}
    seen = 0
    for text in _results(image_bytes, _logger(diag)):
        ch = first_char(text)
        if not ch or not _JP_CHAR.match(ch):
            continue
        counts[ch] = counts.get(ch, 0) + 1
        seen += 1
        if counts[ch] > votes // 2 or seen >= votes:
            break
    if not counts:
        return ''
    best = max(counts.values())
    return next(ch for ch, n in counts.items() if n == best)  # 同数なら先に出た方


def prefecture_of(image_bytes: bytes, diag=None):
    """住所画像から都道府県名を取り出す（47 都道府県のどれかに一致した結果だけを採用）。"""
    return prefecture(recognize(image_bytes, accept=lambda t: bool(prefecture(t)), diag=diag))


def first_char(text: str):
    """氏名の冒頭一字（空白・記号を除いた最初の文字）。"""
    for ch in text:
        if ch.isalnum():
            return ch
    return ''


def prefecture(text: str):
    """住所文字列の先頭付近から都道府県名を探す。"""
    hits = [(text.find(p), p) for p in PREFECTURES if p in text]
    return min(hits)[1] if hits else ''
